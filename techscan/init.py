"""Interactive wizard: `techscan init` generates a config YAML for a new event."""
from __future__ import annotations

import re
import sys
from datetime import datetime, timezone
from pathlib import Path


def _ask(prompt: str, default: str = "", required: bool = True) -> str:
    suffix = f" [{default}]" if default else ""
    while True:
        try:
            answer = input(f"  {prompt}{suffix}: ").strip()
        except (EOFError, KeyboardInterrupt):
            print()
            raise SystemExit(1)
        value = answer or default
        if value or not required:
            return value
        print("    (required)")


def _ask_yn(prompt: str, default: bool = True) -> bool:
    hint = "Y/n" if default else "y/N"
    answer = _ask(f"{prompt} [{hint}]", required=False)
    if not answer:
        return default
    return answer.lower().startswith("y")


def _ask_datetime(prompt: str) -> str:
    print(f"  {prompt}")
    print("    Format: YYYY-MM-DDTHH:MM:SS+HH:MM  (e.g. 2026-11-06T17:00:00+01:00)")
    while True:
        raw = _ask("datetime", required=True)
        # Normalise: accept space between date and time
        raw = raw.replace(" ", "T", 1) if "T" not in raw.upper() else raw
        if raw.endswith("Z"):
            raw = raw[:-1] + "+00:00"
        try:
            dt = datetime.fromisoformat(raw)
            if dt.tzinfo is None:
                print("    Include a UTC offset, e.g. +01:00 or +00:00")
                continue
            return dt.isoformat()
        except ValueError:
            print("    Could not parse that. Try: 2026-11-06T17:00:00+01:00")


def _ask_challenges() -> dict:
    print("\n  Challenges (press Enter with an empty name when done):")
    challenges = {}
    i = 0
    while True:
        i += 1
        name = _ask(f"  Challenge {i} name (or Enter to finish)", required=False)
        if not name:
            if not challenges:
                print("    Need at least one challenge.")
                i -= 1
                continue
            break
        key = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")[:30] or f"challenge_{i}"
        keywords = _ask(f"  Match keywords for '{name}' (comma-separated)", default=key, required=False)
        match_list = [k.strip().lower() for k in keywords.split(",") if k.strip()]
        template = _ask(f"  Template repo URL for '{name}' (or Enter to skip)", required=False)
        ch = {"name": name, "match": match_list}
        if template:
            ch["template"] = template
        challenges[key] = ch
    return challenges


def _ask_partners() -> dict | None:
    if not _ask_yn("\n  Do you have hackerpack / sponsor tools to detect in code?", default=False):
        return None
    print("  Partners (press Enter with an empty name when done):")
    partners = {}
    i = 0
    while True:
        i += 1
        label = _ask(f"  Partner {i} name (or Enter to finish)", required=False)
        if not label:
            break
        key = re.sub(r"[^a-z0-9]+", "_", label.lower()).strip("_")[:20] or f"partner_{i}"
        patterns_raw = _ask(
            f"  Regex patterns to detect '{label}' in code (comma-separated)",
            default=re.escape(label.lower()),
        )
        patterns = [p.strip() for p in patterns_raw.split(",") if p.strip()]
        partners[key] = {"label": label, "patterns": patterns}
    return partners if partners else None


def _build_yaml(data: dict) -> str:
    """Build a commented YAML config string from wizard answers."""
    lines = [
        f"# {data['event_name']} — generated by `techscan init`",
        f"# Edit freely; then run: python -m techscan preflight -c {data['filename']} --ping",
        "",
        "event:",
        f"  name: \"{data['event_name']}\"",
    ]
    if data.get("short_name"):
        lines.append(f"  short_name: \"{data['short_name']}\"")
    if data.get("context"):
        lines.append(f"  context: \"{data['context']}\"")
    if data.get("build_time"):
        lines.append(f"  build_time: \"{data['build_time']}\"")
    lines += [
        f"  start: \"{data['start']}\"",
        f"  deadline: \"{data['deadline']}\"",
    ]
    if data.get("github_org"):
        lines.append(f"  github_org: \"{data['github_org']}\"")
    lines.append("")

    # Challenges
    lines.append("challenges:")
    for key, ch in data["challenges"].items():
        lines.append(f"  {key}:")
        lines.append(f"    name: \"{ch['name']}\"")
        match_str = ", ".join(f'"{m}"' for m in ch.get("match", [key]))
        lines.append(f"    match: [{match_str}]")
        if ch.get("template"):
            lines.append(f"    template: \"{ch['template']}\"")
        if ch.get("data_hints"):
            hints_str = ", ".join(f'"{h}"' for h in ch["data_hints"])
            lines.append(f"    data_hints: [{hints_str}]")
    lines.append("")

    # Partners
    if data.get("partners"):
        lines.append("# Sponsor/partner tools to detect in team code. Patterns are regex, case-insensitive.")
        lines.append("partners:")
        for key, p in data["partners"].items():
            lines.append(f"  {key}:")
            lines.append(f"    label: \"{p['label']}\"")
            pat_str = ", ".join(f"'{pat}'" for pat in p["patterns"])
            lines.append(f"    patterns: [{pat_str}]")
        lines.append("")
    else:
        lines.append("# No partner tools configured. Add a 'partners:' block if your sponsors provide APIs/SDKs.")
        lines.append("# See config/examples/full.yaml for the format.")
        lines.append("")

    # Review
    lines.append("review:")
    lines.append(f"  backend: {data['backend']}")
    if data["backend"] == "anthropic":
        lines.append("  # Set ANTHROPIC_API_KEY in your environment or GitHub secrets.")
    elif data["backend"] == "claude-cli":
        lines.append("  # Uses your Claude Code login. Install Claude Code and run `claude` to authenticate.")
    lines.append(f"  model: {data.get('model', 'claude-sonnet-4-6')}")
    lines.append("  workers: 3")
    lines.append("")

    # Rubric
    lines.append("# Scoring rubric. Adjust criteria, weights and descriptions to match your jury sheet.")
    lines.append("# Remove this block entirely to use the defaults (Concept 4, Prototype 2, Technology 1.5,")
    lines.append("# Potential 1.5, Business 0.5, Wow 0.5).")
    lines.append("# rubric:")
    lines.append("#   criteria:")
    lines.append("#     concept:")
    lines.append("#       label: \"Concept\"")
    lines.append("#       weight: 4")
    lines.append("#       description: \"Does the solution address the challenge?\"")
    lines.append("")

    # Scan
    lines.append("scan:")
    lines.append("  pre_event_grace_hours: 2")
    lines.append("  check_demo_urls: true")
    lines.append("  github_api: true")
    if data.get("extra_secret_patterns"):
        lines.append("  extra_secret_patterns:")
        for pat in data["extra_secret_patterns"]:
            lines.append(f"    - name: \"{pat['name']}\"")
            lines.append(f"      pattern: \"{pat['pattern']}\"")
    lines.append("")

    # Paths
    slug = re.sub(r"[^a-z0-9]+", "-", data["event_name"].lower()).strip("-")[:30]
    lines.append("paths:")
    lines.append(f"  workdir: ../work-{slug}")
    lines.append(f"  output: ../out-{slug}")
    lines.append("")

    return "\n".join(lines) + "\n"


def run_init(output_dir: str = "config") -> int:
    """Interactive wizard that generates a config YAML."""
    print("=" * 60)
    print("  TechScan — New Event Setup")
    print("=" * 60)
    print()

    event_name = _ask("Event name", default="My Hackathon 2026")
    short_name = _ask("Short name (for headers)", default=event_name.split("—")[0].strip()[:20], required=False)
    context = _ask("One-line description (helps the AI reviewer understand the event)", required=False)
    build_time = _ask("How long do teams have to build?", default="about 48 hours", required=False)

    print()
    start = _ask_datetime("Event start (when coding begins):")
    deadline = _ask_datetime("Submission deadline:")

    github_org = _ask("\n  GitHub organisation (for team repos, or Enter to skip)", required=False)

    challenges = _ask_challenges()
    partners = _ask_partners()

    print("\n  AI review backend:")
    print("    1. claude-cli  — uses your Claude Code login (free, needs Claude Code installed)")
    print("    2. anthropic   — uses ANTHROPIC_API_KEY (pay per use)")
    print("    3. offline     — no AI, deterministic checks only")
    backend_choice = _ask("Choose [1/2/3]", default="1")
    backend_map = {"1": "claude-cli", "2": "anthropic", "3": "offline",
                   "claude-cli": "claude-cli", "anthropic": "anthropic", "offline": "offline"}
    backend = backend_map.get(backend_choice, "claude-cli")

    model = "claude-sonnet-4-6"
    if backend != "offline":
        model = _ask("AI model", default="claude-sonnet-4-6")

    slug = re.sub(r"[^a-z0-9]+", "-", event_name.lower()).strip("-")[:30]
    filename = f"{slug}.yaml"

    data = {
        "event_name": event_name,
        "short_name": short_name,
        "context": context,
        "build_time": build_time,
        "start": start,
        "deadline": deadline,
        "github_org": github_org,
        "challenges": challenges,
        "partners": partners,
        "backend": backend,
        "model": model,
        "filename": f"{output_dir}/{filename}",
    }

    yaml_content = _build_yaml(data)

    out_path = Path(output_dir) / filename
    out_path.parent.mkdir(parents=True, exist_ok=True)
    if out_path.exists():
        if not _ask_yn(f"\n  {out_path} already exists. Overwrite?", default=False):
            print("  Aborted.")
            return 1

    out_path.write_text(yaml_content, encoding="utf-8")
    print(f"\n  Config written to {out_path}")
    print(f"\n  Next steps:")
    print(f"    1. Review and edit:  {out_path}")
    print(f"    2. Preflight check:  python -m techscan preflight -c {out_path} --ping")
    print(f"    3. Try a demo:       python -m techscan demo")
    print(f"    4. Run the scan:     python -m techscan scan -c {out_path} -s submissions.csv")
    return 0
